/** Dịch một thể loại Google Books sang tiếng Việt (giữ nguyên nếu không có trong bảng). */
export function translateCategory(cat?: string, fallback = 'Tổng hợp'): string {
  if (!cat) return fallback;
  // Google Books có thể trả "BUSINESS & ECONOMICS / General": lấy phần đầu
  const first = cat.split('/')[0].trim();
  return CATEGORY_VI[first.toLowerCase()] || first;
}
